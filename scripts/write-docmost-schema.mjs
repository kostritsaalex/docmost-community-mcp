// Turns the output of dump-docmost-schema.cjs into src/docmost-schema.ts.
//   node scripts/write-docmost-schema.mjs docmost-schema.json
// The dump may start with log lines from Docmost; the schema is its last non-empty line.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) {
  console.error("Usage: node scripts/write-docmost-schema.mjs <dump.json>");
  process.exit(1);
}

const lines = readFileSync(input, "utf8").split(/\r?\n/).filter((line) => line.trim() !== "");
const dump = JSON.parse(lines[lines.length - 1]);
for (const key of ["docmostVersion", "topNode", "nodes", "marks"]) {
  if (!(key in dump)) {
    console.error(`The dump has no "${key}"; is it the output of dump-docmost-schema.cjs?`);
    process.exit(1);
  }
}

const target = fileURLToPath(new URL("../src/docmost-schema.ts", import.meta.url));
const source = `// Generated by scripts/write-docmost-schema.mjs from the schema of a running Docmost
// (scripts/dump-docmost-schema.cjs). Do not edit by hand: dump and regenerate after a Docmost upgrade.
import type { SchemaDump } from "./doc-schema.js";

export const DOCMOST_SCHEMA: SchemaDump = ${JSON.stringify(dump, null, 2)};
`;
writeFileSync(target, source);
console.log(`Wrote ${target}: Docmost ${dump.docmostVersion}, ${dump.nodes.length} node types, ${dump.marks.length} mark types.`);
